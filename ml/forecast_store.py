"""Persist forecast runs, daily forecasts and backtest accuracy in PostgreSQL."""

from __future__ import annotations

import json
import math
import uuid

import pandas as pd
from psycopg2.extras import execute_values
from sqlalchemy import text
from sqlalchemy.engine import Connection


def _raw(conn: Connection):
    c = conn.connection
    return getattr(c, "dbapi_connection", c)


def _num(v):
    if v is None:
        return None
    try:
        f = float(v)
    except (TypeError, ValueError):
        return None
    return None if math.isnan(f) or math.isinf(f) else round(f, 4)


def create_run(conn: Connection, *, job_id: str | None, run_type: str, model_name: str, price_model_name: str | None,
               demand_model_version: str | None, price_model_version: str | None, mlflow_run_id: str | None,
               price_mlflow_run_id: str | None, data_start, cutoff, horizon: int, products: int,
               metrics: dict) -> str:
    run_id = str(uuid.uuid4())
    conn.execute(text("""
        INSERT INTO forecast_runs (run_id, job_id, run_type, model_name, price_model_name, demand_model_version,
            price_model_version, mlflow_run_id, price_mlflow_run_id, data_start_date, cutoff_date, horizon_days,
            products_forecast, status, metrics)
        VALUES (CAST(:run_id AS uuid), CAST(:job_id AS uuid), :run_type, :model_name, :price_model_name,
            :dv, :pv, :mrid, :prid, :ds, :cutoff, :h, :n, 'succeeded', CAST(:metrics AS jsonb))"""),
        {"run_id": run_id, "job_id": job_id, "run_type": run_type, "model_name": model_name,
         "price_model_name": price_model_name, "dv": demand_model_version, "pv": price_model_version,
         "mrid": mlflow_run_id, "prid": price_mlflow_run_id, "ds": data_start, "cutoff": cutoff, "h": horizon,
         "n": products, "metrics": json.dumps(metrics, default=str)})
    return run_id


def insert_forecasts(conn: Connection, run_id: str, frame: pd.DataFrame, sku_to_id: dict[str, int],
                     generated_at, model_run_id: str | None) -> int:
    """frame: date, sku, forecast, lower, upper, price_forecast, price_lower, price_upper."""
    rows = []
    for r in frame.itertuples(index=False):
        price = _num(getattr(r, "price_forecast", None))
        rows.append((run_id, sku_to_id[str(r.sku)], generated_at, pd.Timestamp(r.date).date(),
                     _num(r.forecast) or 0.0, _num(r.lower), _num(r.upper), price,
                     _num(getattr(r, "price_lower", None)) if price is not None else None,
                     _num(getattr(r, "price_upper", None)) if price is not None else None,
                     "forecast" if price is not None else "unavailable", model_run_id))
    with _raw(conn).cursor() as cur:
        execute_values(cur, """INSERT INTO forecasts (run_id, product_id, generated_at, forecast_date,
            demand_prediction, demand_lower, demand_upper, price_prediction, price_lower, price_upper, price_status,
            model_run_id) VALUES %s""", rows, page_size=5000)
    return len(rows)


def insert_accuracy(conn: Connection, run_id: str, target: str, per_model: dict[str, pd.DataFrame],
                    selected: str, sku_to_id: dict[str, int]) -> int:
    rows = []
    for model, df in per_model.items():
        for r in df.itertuples(index=False):
            if str(r.sku) not in sku_to_id:
                continue
            rows.append((run_id, sku_to_id[str(r.sku)], target, model, _num(r.mae), _num(r.rmse), _num(r.wape),
                         _num(r.bias), _num(r.mape), int(r.n_obs), model == selected))
    with _raw(conn).cursor() as cur:
        execute_values(cur, """INSERT INTO model_accuracy (run_id, product_id, target, model_name, mae, rmse, wape,
            bias, mape, n_obs, is_selected) VALUES %s""", rows, page_size=5000)
    return len(rows)


def prune_backtest_runs(conn: Connection, keep_job_id: str) -> int:
    """Backtest runs are regenerated by every job; keep only the latest job's."""
    return conn.execute(text("""DELETE FROM forecast_runs WHERE run_type = 'backtest'
                                AND job_id IS DISTINCT FROM CAST(:j AS uuid)"""), {"j": keep_job_id}).rowcount
